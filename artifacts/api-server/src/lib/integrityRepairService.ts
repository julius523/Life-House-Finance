export type IntegrityRepairCheckKey =
  | "expense_draft_no_link"
  | "bill_accrual_draft_no_link"
  | "bill_payment_draft_no_link";

export type IntegrityRepairDescriptor = {
  /** Sweep check key this entry repairs (1:1 with integritySweepService). */
  checkKey: IntegrityRepairCheckKey;
  /** Operator-facing label shown in the confirmation modal. */
  label: string;
  /**
   * Plain-English description of the change the registry will apply.
   * Surfaced in the UI confirmation modal verbatim — keep concise.
   */
  description: string;
  /** Operator-facing label for the entity behind each ID. */
  idLabel: string;
  fn: RepairFn;
};

export const INTEGRITY_REPAIR_REGISTRY: ReadonlyArray<IntegrityRepairDescriptor> = [
  {
    checkKey: "expense_draft_no_link",
    label: "Re-link expense → draft",
    description:
      "Re-creates the missing accounting_source_links row from the existing draft (matched by the draft's memo suffix `(expense #N)`).",
    idLabel: "expense",
    fn: repairExpenseDraftNoLink,
  },
  {
    checkKey: "bill_accrual_draft_no_link",
    label: "Re-link bill accrual → draft",
    description:
      "Re-creates the missing accrual accounting_source_links row from the existing draft (matched by the draft's memo suffix `(bill #N)`).",
    idLabel: "bill",
    fn: repairBillAccrualDraftNoLink,
  },
  {
    checkKey: "bill_payment_draft_no_link",
    label: "Re-link bill payment → draft",
    description:
      "Re-creates the missing payment accounting_source_links row from the existing draft (matched by the draft's memo prefix `Payment of bill #N`).",
    idLabel: "bill",
    fn: repairBillPaymentDraftNoLink,
  },
];

export const INTEGRITY_REPAIR_KEYS: ReadonlyArray<IntegrityRepairCheckKey> =
  INTEGRITY_REPAIR_REGISTRY.map((d) => d.checkKey);

export function getRepairDescriptor(
  checkKey: string,
): IntegrityRepairDescriptor | null {
  return (
    INTEGRITY_REPAIR_REGISTRY.find((d) => d.checkKey === checkKey) ?? null
  );
}

/**
 * Public-safe summary of the registry — what the UI loads to decide
 * which sweep rows get a "Repair…" affordance.
 */
export type IntegrityRepairSummary = {
  checkKey: IntegrityRepairCheckKey;
  label: string;
  description: string;
  idLabel: string;
};

export function describeRegistry(): IntegrityRepairSummary[] {
  return INTEGRITY_REPAIR_REGISTRY.map((d) => ({
    checkKey: d.checkKey,
    label: d.label,
    description: d.description,
    idLabel: d.idLabel,
  }));
}
