export const JOURNAL_ENTRY_LINE_TYPES = ["debit", "credit"] as const;
export type JournalEntryLineType = (typeof JOURNAL_ENTRY_LINE_TYPES)[number];

export const journalEntryLinesTable = pgTable(
  "journal_entry_lines",
  {
    id: serial("id").primaryKey(),
    journalEntryId: integer("journal_entry_id")
      .notNull()
      .references(() => journalEntriesTable.id, { onDelete: "restrict" }),
    lineNo: integer("line_no").notNull(),
    type: text("type").notNull(),
    /**
     * Stored as positive cents on whichever side (`type`) the line is on —
     * NEVER floats. Balance check is `sum(debit cents) == sum(credit cents)`.
     */
    amountCents: integer("amount_cents").notNull(),
    account: text("account").notNull(),
    program: text("program"),
    fund: text("fund"),
    memo: text("memo"),
  },
  (table) => [
    index("journal_entry_lines_je_idx").on(table.journalEntryId, table.lineNo),
    uniqueIndex("journal_entry_lines_je_lineno_uniq").on(
      table.journalEntryId,
      table.lineNo,
    ),
  ],
);

export type JournalEntryLineRow = typeof journalEntryLinesTable.$inferSelect;
export type JournalEntryLineInsert =
  typeof journalEntryLinesTable.$inferInsert;
